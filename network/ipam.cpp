#include <cstdint>
#include <cstdio>
#include <map>
#include <set>
#include <string>
#include <string_view>
#include <vector>
#include "../mediation/csv.h"

/* management address assignment report.
   the mgmt plane is 10.20.0.0/16, has been since the 2009 build.
   assignments live in devices.csv, everything else (routing-tables/,
   firewall-rules/, dns-zones/, snmp-polling.conf) is generated by hand from
   this file and then edited in place, so they drift. */

namespace {

std::uint32_t ip_to_u32(std::string_view ip) {
  unsigned parts[4] = {0, 0, 0, 0};
  const std::string text(ip);
  std::sscanf(text.c_str(), "%u.%u.%u.%u", &parts[0], &parts[1], &parts[2], &parts[3]);
  return (parts[0] << 24) | (parts[1] << 16) | (parts[2] << 8) | parts[3];
}

std::string device_field(const Row &r, const std::string &key) {
  auto it = r.find(key);
  return it == r.end() ? std::string{} : it->second;
}

}  // namespace

int main(int argc, char **argv) {
  std::string devices = "network/devices.csv";
  for (int i = 1; i < argc; i++) {
    std::string_view a = argv[i];
    if (a == "--devices" && i + 1 < argc) devices = argv[++i];
  }
  const std::vector<Row> rows = read_csv(devices);
  if (rows.empty()) {
    std::fprintf(stderr, "no device file at %s\n", devices.c_str());
    return 1;
  }
  std::map<std::string, int> per_third_octet;
  std::set<std::string> seen;
  int dupes = 0, reserved = 0;
  for (const Row &r : rows) {
    const std::string ip = device_field(r, "mgmt_ip");
    if (seen.contains(ip)) {
      std::printf("DUPLICATE %s %s\n", ip.c_str(), device_field(r, "device_name").c_str());
      dupes++;
    }
    seen.insert(ip);
    const std::uint32_t third = (ip_to_u32(ip) >> 8) & 0xff;
    per_third_octet["10.20." + std::to_string(third) + ".0/24"]++;
    if (third == 250) reserved++;
  }
  std::printf("supernet 10.20.0.0/16\n");
  std::printf("devices %d, addresses in use %d, internal duplicates %d\n",
              static_cast<int>(rows.size()), static_cast<int>(seen.size()), dupes);
  std::printf("addresses inside reserved 10.20.250.0/24: %d\n", reserved);
  for (const auto &[subnet, count] : per_third_octet) {
    std::printf("  %-18s %d\n", subnet.c_str(), count);
  }
  return 0;
}
